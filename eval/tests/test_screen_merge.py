"""Screening a few titles again without throwing away the rest of the pool.

Everything here is FABRICATED FOR TEST ONLY: an invented earlier report with two rows, and a
one second clip of flat grey generated by ffmpeg in a temporary directory. The grey clip is not
hazardous and nothing opens it in a player; flashmap analyses it the same way it analyses
anything, and finds nothing, which is the point. No real screening runs and nothing here writes
to results/.

What this holds the merge to:

- the rows for the named files are replaced and every other row survives untouched, so a
  re-run of four titles does not quietly drop the other sixteen;
- the file says which titles were re-run and when, so a merged report never reads as one run;
- --only refuses when there is no report to merge into, and when a named file is not there.
  Either way it writes nothing, because half a screening written over a whole one is the worst
  outcome available.

To see them fail on purpose: see the note on each test. All four were verified Sep 17, 2026.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

EVAL_DIR = Path(__file__).resolve().parents[1]
SCREEN = EVAL_DIR / "screen.py"

FABRICATED_FOR_TEST_ONLY = True

KEPT = "HAZARD_invented_kept.mp4"
RESCREENED = "HAZARD_invented_rescreened.mp4"

EARLIER_RUN = {
    "generated_on": "2026-09-16",
    "profile": "wcag",
    "adapter_entry_point": "flashmap.analyze_file(path, profile)",
    "clips_analyzed_ok": 1,
    "clips_failed": 1,
    "per_source": {"Invented source": {"files": 1, "flagged_files": 1, "flagged_segments": 4}},
    "per_file": [
        {
            "file": KEPT,
            "source": "Invented source",
            "flagged_segments": 4,
            "frame_count": 500,
            "variable_frame_rate": False,
            "segments": [
                {
                    "start_s": 0.0,
                    "end_s": 2.0,
                    "reason": "general",
                    "area_fraction": 0.5,
                    "triggered_by": ["wcag-10deg"],
                    "breaks_baseline": True,
                    "max_flashes_in_window": 8,
                }
            ]
            * 4,
        },
        {
            "file": RESCREENED,
            "source": "Invented source",
            "error": "fabricated decode failure, for test only",
        },
    ],
    "totals": {"clips": 2, "flagged_segments": 4, "sources_with_at_least_one_flag": 1},
    "gate2": {"min_segments": 15, "min_sources": 4, "passes": False, "note": "fabricated"},
    "renamed_to_hazard": [],
}

LEDGER_ROWS = (
    "file,source_page_url,license,credit_line,sha256,duration_s,resolution,"
    "license_checked_on,notes\n"
    f"{KEPT},https://example.invalid/a,CC BY 4.0,Invented for test only,"
    "aa,100,640x480,2026-09-17,source: Invented source. FABRICATED FOR TEST ONLY.\n"
    f"{RESCREENED},https://example.invalid/b,CC BY 4.0,Invented for test only,"
    "bb,1,320x240,2026-09-17,source: Invented source. FABRICATED FOR TEST ONLY.\n"
)


def _setup(tmp_path: Path) -> tuple[Path, Path]:
    """A media directory holding one flat grey second, its ledger, and an earlier report."""
    if shutil.which("ffmpeg") is None:
        pytest.skip("ffmpeg is not on the path")
    media = tmp_path / "media"
    media.mkdir()
    made = subprocess.run(
        [
            "ffmpeg", "-v", "error", "-y",
            "-f", "lavfi", "-i", "color=c=gray:s=320x240:r=25:d=1",
            "-c:v", "libx264", "-pix_fmt", "yuv420p",
            str(media / RESCREENED),
        ],
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert made.returncode == 0, made.stderr
    (media / "LICENSES.csv").write_text(LEDGER_ROWS)

    out = tmp_path / "screening.json"
    out.write_text(json.dumps(EARLIER_RUN, indent=2) + "\n")
    return media, out


def _run(media: Path, out: Path, extra: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [
            sys.executable,
            str(SCREEN),
            "--media-dir",
            str(media),
            "--out",
            str(out),
            "--no-rename",
            *extra,
        ],
        capture_output=True,
        text=True,
        timeout=600,
    )


def test_the_rows_not_named_survive_a_rescreen(tmp_path):
    """Break it: replace per_file instead of merging, and this goes red."""
    media, out = _setup(tmp_path)
    finished = _run(media, out, ["--only", "invented_rescreened.mp4"])
    assert finished.returncode == 0, finished.stderr

    report = json.loads(out.read_text())
    files = {row["file"]: row for row in report["per_file"]}
    assert set(files) == {KEPT, RESCREENED}

    # The row nobody asked to re-run is exactly what the earlier run wrote.
    assert files[KEPT] == EARLIER_RUN["per_file"][0]
    # The re-run row is no longer an error, and carries this run's answer: flat grey flashes
    # at nothing, so no segment.
    assert "error" not in files[RESCREENED], files[RESCREENED]
    assert files[RESCREENED]["flagged_segments"] == 0
    assert files[RESCREENED]["source"] == "Invented source"

    assert report["clips_analyzed_ok"] == 2
    assert report["clips_failed"] == 0
    assert report["totals"]["clips"] == 2
    assert report["totals"]["flagged_segments"] == 4


def test_the_report_says_which_titles_were_rescreened(tmp_path):
    """Break it: drop the rescreens block, and a merged file reads as one run."""
    media, out = _setup(tmp_path)
    finished = _run(media, out, ["--only", "invented_rescreened.mp4"])
    assert finished.returncode == 0, finished.stderr

    report = json.loads(out.read_text())
    assert report["rescreens"], "the merge left no record of itself"
    entry = report["rescreens"][-1]
    assert entry["files"] == [RESCREENED]
    assert entry["rows_kept_from_the_earlier_run"] == 1


def test_only_refuses_when_there_is_nothing_to_merge_into(tmp_path):
    """Break it: let --only write a fresh report, and this goes red."""
    media, out = _setup(tmp_path)
    out.unlink()
    finished = _run(media, out, ["--only", "invented_rescreened.mp4"])
    assert finished.returncode == 2
    assert "merges into an existing" in finished.stderr
    assert not out.exists()


def test_only_refuses_a_file_that_is_not_there(tmp_path):
    """Break it: silently screen nothing, and this goes red with the report untouched."""
    media, out = _setup(tmp_path)
    before = out.read_text()
    finished = _run(media, out, ["--only", "invented_that_does_not_exist.mp4"])
    assert finished.returncode == 2
    assert "invented_that_does_not_exist" in finished.stderr
    assert out.read_text() == before
