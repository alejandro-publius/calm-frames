"""Selected-target package gates use real Node and synthetic tar fixtures."""
from __future__ import annotations

import hashlib
import io
import json
import shutil
import subprocess
import tarfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def gate(tmp_path):
    app = tmp_path / 'app'
    script = app / 'tools/check_prepared_library.mjs'
    script.parent.mkdir(parents=True)
    shutil.copy2(ROOT / 'app/tools/check_prepared_library.mjs', script)
    root = app / 'assets/raw/prepared-library'
    root.mkdir(parents=True)
    raw = '{"version":1,"titles":[]}'
    (root / 'catalog.json').write_text(raw)
    (root / 'catalog.ts').write_text(
        '/** Generated by pipeline.packaged_library. Verify before building the app. */\n'
        f'export const PACKAGED_LIBRARY_JSON = {json.dumps(raw)};\n'
        f'export const PACKAGED_LIBRARY_SHA256 = {json.dumps(hashlib.sha256(raw.encode()).hexdigest())};\n')

    def package(arch, kind='debug', corrupt=False):
        dest = app / f'build/{arch}-{kind}/calm-frames-app_{arch}.vpkg'
        dest.parent.mkdir(parents=True, exist_ok=True)
        with tarfile.open(dest, 'w') as archive:
            for path in root.iterdir():
                data = b'changed' if corrupt and path.name == 'catalog.json' else path.read_bytes()
                info = tarfile.TarInfo(f'assets/raw/prepared-library/{path.name}')
                info.size = len(data)
                archive.addfile(info, io.BytesIO(data))

    def run(*args):
        return subprocess.run(['node', str(script), *args], text=True, capture_output=True, timeout=15)

    return package, run


@pytest.mark.parametrize('arch,kind', [('aarch64', 'Debug'), ('x86_64', 'Release'), ('armv7', 'Release')])
def test_single_selected_package_does_not_require_other_architectures(gate, arch, kind):
    package, run = gate
    package(arch, kind.lower())
    result = run('--packages', kind, '--arch', arch)
    assert result.returncode == 0, result.stderr


def test_original_all_architectures_invocation_still_requires_all(gate):
    package, run = gate
    package('aarch64')
    assert run('--packages', 'Debug').returncode != 0
    package('armv7')
    package('x86_64')
    assert run('--packages', 'Debug').returncode == 0


@pytest.mark.parametrize('args', [('--arch', 'mips'), ('--arch',), ('--unknown', 'aarch64'), ('--arch', 'aarch64', 'extra')])
def test_unknown_or_incomplete_target_options_are_refused(gate, args):
    package, run = gate
    for arch in ('armv7', 'aarch64', 'x86_64'):
        package(arch)
    assert run('--packages', 'Debug', *args).returncode != 0


def test_selected_package_still_requires_exact_prepared_bytes(gate):
    package, run = gate
    package('aarch64', corrupt=True)
    assert run('--packages', 'Debug', '--arch', 'aarch64').returncode != 0


def test_delivery_refuses_a_missing_compiled_bundle_even_when_primary_catalog_is_valid(tmp_path):
    raw = '{"version":1,"titles":[]}'
    module = '/** Generated by pipeline.packaged_library. Verify before building the app. */\n' + (
        f'export const PACKAGED_LIBRARY_JSON = {json.dumps(raw)};\n'
        f'export const PACKAGED_LIBRARY_SHA256 = {json.dumps(hashlib.sha256(raw.encode()).hexdigest())};\n')
    test = tmp_path / 'missing-bundle.mjs'
    test.write_text(
        f'import {{ checkPreparedNamespace }} from {json.dumps((ROOT / "app/tools/check_prepared_library.mjs").as_uri())};\n'
        f'const files = {json.dumps({"catalog.json": raw, "catalog.ts": module})};\n'
        'try { checkPreparedNamespace(Object.keys(files), name => Buffer.from(files[name]), undefined, '
        '{requiredBundles: ["a".repeat(64)]}); process.exit(2); } '
        'catch (error) { if (!error.message.includes("compiled prepared bundle is missing")) throw error; }\n')
    result = subprocess.run(['node', str(test)], capture_output=True, text=True, timeout=15)
    assert result.returncode == 0, result.stderr
