"""Bundle the practice demo's signed hold stills as package assets.

The Vega image loader refuses a data URI, which is how the signed map carries
each still, so on the device a practice hold showed black instead of the calm
scene the map was signed with. This writes the same bytes out of
app/src/calmframes/benignStoryData.ts as JPEG files under
app/assets/raw/benign-story/stills/ and generates
app/src/calmframes/benignStoryStills.ts, a registry the player uses to draw a
bundled copy for exactly the hold it would otherwise draw from the data URI.

The copy is checked, not trusted: every registry entry carries the SHA-256 of
the still's bytes, app/test/calmframes/benignStoryStills.test.ts hashes the
bundled file and the data URI and refuses any difference, and ``--check`` here
does the same from the repository root.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "app/src/calmframes/benignStoryData.ts"
STILLS = REPO / "app/assets/raw/benign-story/stills"
REGISTRY = REPO / "app/src/calmframes/benignStoryStills.ts"
PROFILES = ("wcag", "broadcast", "extra-cautious")
PREFIX = "data:image/jpeg;base64,"


def maps() -> dict[str, dict]:
    text = DATA.read_text()
    out: dict[str, dict] = {}
    for profile in PROFILES:
        match = re.search(r'"%s": ("(?:[^"\\]|\\.)*")' % re.escape(profile), text)
        if not match:
            raise SystemExit(f"{DATA}: no map for {profile}")
        out[profile] = json.loads(json.loads(match.group(1)))
    return out


def holds(map_json: dict) -> list[dict]:
    block = map_json.get("scene_holds")
    if isinstance(block, dict) and isinstance(block.get("holds"), list):
        return block["holds"]
    if isinstance(map_json.get("holds"), list):
        return map_json["holds"]
    raise SystemExit("map carries no scene holds")


def whole(value: float | int) -> int | float:
    """5000.0 in the map is the number 5000 in the registry."""
    return int(value) if float(value).is_integer() else value


def collect() -> tuple[dict[str, list[dict]], dict[str, bytes]]:
    entries: dict[str, list[dict]] = {}
    files: dict[str, bytes] = {}
    for profile, map_json in maps().items():
        entries[profile] = []
        for hold in holds(map_json):
            uri = hold["image_data_uri"]
            if not uri.startswith(PREFIX):
                raise SystemExit(f"{profile}: still is not a JPEG data URI")
            data = base64.b64decode(uri[len(PREFIX):], validate=True)
            sha = hashlib.sha256(data).hexdigest()
            name = f"still-{sha[:16]}.jpg"
            files[name] = data
            entries[profile].append({"sha256": sha, "startMs": whole(hold["start_ms"]), "endMs": whole(hold["end_ms"]), "file": name})
    return entries, files


def registry_text(entries: dict[str, list[dict]]) -> str:
    lines = [
        "/**",
        " * Generated by eval/benign_story_stills.py from benignStoryData.ts. Do not edit.",
        " *",
        " * Bundled copies of the practice demo's signed hold stills, one per hold and",
        " * profile, because the device's image loader refuses the data URI the signed",
        " * map carries. Each entry names the SHA-256 of the bytes; the test beside the",
        " * generator hashes both the file and the data URI and refuses any difference.",
        " */",
        "import type { ImageSourcePropType } from 'react-native';",
        "",
        "export interface BundledStill {",
        "  sha256: string;",
        "  startMs: number;",
        "  endMs: number;",
        "  source: ImageSourcePropType;",
        "}",
        "",
        "export const BENIGN_STORY_STILLS: Record<string, BundledStill[]> = {",
    ]
    for profile in PROFILES:
        lines.append(f"  '{profile}': [")
        for entry in entries[profile]:
            lines.append(
                f"    {{ sha256: '{entry['sha256']}', startMs: {entry['startMs']}, endMs: {entry['endMs']},"
                f" source: require('../../assets/raw/benign-story/stills/{entry['file']}') }},"
            )
        lines.append("  ],")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse any drift instead of writing")
    args = parser.parse_args(argv)
    entries, files = collect()
    text = registry_text(entries)
    if args.check:
        problems = []
        if not REGISTRY.exists() or REGISTRY.read_text() != text:
            problems.append(f"{REGISTRY.relative_to(REPO)} differs from what the generator writes")
        for name, data in files.items():
            path = STILLS / name
            if not path.exists() or path.read_bytes() != data:
                problems.append(f"{path.relative_to(REPO)} is missing or differs from the signed still")
        for extra in sorted(STILLS.glob("*.jpg")) if STILLS.exists() else []:
            if extra.name not in files:
                problems.append(f"{extra.relative_to(REPO)} is not one of the signed stills")
        for problem in problems:
            print(problem)
        print("benign story stills: " + ("drift" if problems else "current"))
        return 1 if problems else 0
    STILLS.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (STILLS / name).write_bytes(data)
    REGISTRY.write_text(text)
    for profile, items in entries.items():
        print(profile, [(e["startMs"], e["endMs"], e["file"]) for e in items])
    print(f"wrote {len(files)} still file(s) and {REGISTRY.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
